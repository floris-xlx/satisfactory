export const recipesById: Record<string, Recipe> = Object.fromEntries(
  recipes.map((r) => [r.id, r]),
)

export function getRecipe(id: string): Recipe {
  const r = recipesById[id]
  if (!r) throw new Error(`Unknown recipe: ${id}`)
  return r
}

/** Default (non-alternate) recipes that produce an item as primary output. */
export function recipesProducing(itemId: string): Recipe[] {
  return recipes.filter((r) => r.outputs.some((o) => o.itemId === itemId))
}

export function defaultRecipeFor(itemId: string): Recipe | undefined {
  const list = recipesProducing(itemId)
  return list.find((r) => !r.isAlternate) ?? list[0]
}
